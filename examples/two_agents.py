"""Two independent agents sharing one authorized memory store (spec §12 + §18 acceptance scenario).

Run the API first:  memory-mesh serve
Then:               MESH_ADMIN_KEY=$(memory-mesh admin-key) python examples/two_agents.py

If MESH_LLM_PROVIDER is configured on the server, Agent B's reply is generated by that LLM through
/v1 context; otherwise this script prints the compiled personalized context Agent B would send to its model."""
import os, json, uuid
from memory_mesh_sdk import MemoryMesh

URL = os.getenv("MESH_URL", "http://127.0.0.1:8765")
owner = MemoryMesh(api_key=os.environ["MESH_ADMIN_KEY"], base_url=URL)
user = "demo_" + uuid.uuid4().hex[:6]
sfx = uuid.uuid4().hex[:4]

a = owner.admin.create_agent("Advisor (Agent A)", id=f"advisor_{sfx}")
b = owner.admin.create_agent("Analyst (Agent B)", id=f"analyst_{sfx}")
owner.admin.grant(user, a["id"], ["events:write", "memory:read", "memory:write"], note="user consented in app A")
owner.admin.grant(user, b["id"], ["memory:read", "context:read", "human:read", "semantic:read", "semantic:write",
                                  "mind:read"], source_agents=[a["id"]], note="user allowed B to read A's memories")
A = MemoryMesh(api_key=a["api_key"], base_url=URL)
B = MemoryMesh(api_key=b["api_key"], base_url=URL)

print("== 1. User tells Agent A a preference")
r = A.events.ingest(user, "I prefer business advice that contains new information, precise evidence, "
                          "and actionable decisions.")
print("   memories:", [m["memory"] for m in r["memories"]])
print("   observations:", [(o["kind"], o["statement"]) for o in r["observations"]])

task = "Make this analysis more sophisticated."
print(f"\n== 2. User tells Agent B: '{task}'")
ctx = B.context.build(user, task)
print(ctx["prompt"])
print("   ambiguous terms without learned meaning:",
      [t["id"] for t in ctx["trace"] if t.get("uncertain")])

print("\n== 3. Semantic Arena: two contrasting interpretations of 'sophisticated'")
cmp = B.semantic.compare(user, "sophisticated", context="business writing")  # actively selected pair
for c in cmp["candidates"]:
    print(f"   [{c['id']}] {c['label']}: {c['text']}  (predicted p={cmp['predicted'][c['id']]})")
choice = "insight" if any(c["id"] == "insight" for c in cmp["candidates"]) else cmp["candidates"][0]["id"]
print(f"\n== 4. User picks '{choice}'")
fb = B.semantic.feedback(user, cmp["id"], choice)
print("   weight change:", json.dumps(fb["weight_delta"]))
print("   recorded observation:", fb["observation"]["statement"])

print("\n== 5. Agent B's next context now uses that feedback")
ctx2 = B.context.build(user, task, context="business writing")
print(ctx2["prompt"])

print("\n== 6. Provenance (owner view)")
for m in owner.memory.list(user):
    print("  ", m["memory"][:60], "| written by", m["metadata"]["mesh_source_agent"], "| event",
          m["metadata"]["mesh_provenance"]["id"])
print("   user id:", user)
